import { CloudSyncService } from './cloudSyncService';

export type SubscriptionPlan = '30D' | '90D' | '365D' | 'LIFETIME';

export interface LicenseInfo {
  key: string;
  plan: SubscriptionPlan;
  planName: string;
  createdAt: number;
  expiresAt: number;
  clientNotes?: string;
  isRevoked?: boolean;
  workspaceId?: string;
  companyName?: string;
  employeeSeats?: number;
}

export interface UserSubscriptionState {
  status: 'free_trial' | 'active' | 'expired';
  freeTrialsUsed: number;
  maxFreeTrials: number;
  activeLicense?: LicenseInfo;
  daysRemaining?: number;
}

const USER_SUB_STORAGE_KEY = 'pitchboss_user_subscription_v1';
const ADMIN_LICENSES_KEY = 'pitchboss_admin_generated_licenses_v1';
const SECRET_SALT = 'PITCHBOSS_VIP_2026';

export class SubscriptionService {
  /**
   * Translates plan code into human-friendly description
   */
  public static getPlanDetails(plan: SubscriptionPlan): { name: string; durationDays: number; priceEuro: number } {
    switch (plan) {
      case '30D':
        return { name: 'Pase Mensual (30 Días)', durationDays: 30, priceEuro: 19 };
      case '90D':
        return { name: 'Pase Trimestral (90 Días)', durationDays: 90, priceEuro: 45 };
      case '365D':
        return { name: 'Pase Anual (1 Año)', durationDays: 365, priceEuro: 120 };
      case 'LIFETIME':
        return { name: 'Pase Vitalicio (Ilimitado)', durationDays: 3650, priceEuro: 299 };
      default:
        return { name: 'Pase Mensual (30 Días)', durationDays: 30, priceEuro: 19 };
    }
  }

  /**
   * Generates a tamper-resistant deterministic checksum for a key
   */
  private static generateChecksum(plan: string, expiryMs: number): string {
    const raw = `${plan}-${expiryMs}-${SECRET_SALT}`;
    let hash = 0;
    for (let i = 0; i < raw.length; i++) {
      hash = ((hash << 5) - hash) + raw.charCodeAt(i);
      hash |= 0;
    }
    return Math.abs(hash).toString(16).toUpperCase().padStart(4, '0').slice(-4);
  }

  /**
   * Generates a new license key (Used by Admin)
   */
  public static generateAdminLicense(
    plan: SubscriptionPlan,
    clientNotes?: string,
    workspaceId?: string,
    companyName?: string,
    employeeSeats?: number
  ): LicenseInfo {
    const details = this.getPlanDetails(plan);
    const now = Date.now();
    const expiresAt = now + details.durationDays * 24 * 60 * 60 * 1000;
    
    // Format: PB-{PLAN}-{EXPIRY_HEX}-{CHECKSUM}
    const expiryHex = expiresAt.toString(16).toUpperCase();
    const checksum = this.generateChecksum(plan, expiresAt);
    const key = `PB-${plan}-${expiryHex}-${checksum}`;

    const ws = workspaceId || 'default';
    const compName = companyName || (ws === 'tepic-madrid' ? 'Restaurante Tepic (Ayala 14)' : ws === 'lovo-bar' ? 'LOVO Bar & Hospitality' : 'General');
    const seats = employeeSeats && employeeSeats > 0 ? employeeSeats : 10;

    const license: LicenseInfo = {
      key,
      plan,
      planName: details.name,
      createdAt: now,
      expiresAt,
      clientNotes: clientNotes?.trim() || 'Cliente Directo',
      isRevoked: false,
      workspaceId: ws,
      companyName: compName,
      employeeSeats: seats
    };

    // Store in admin registry
    const registry = this.getRawAdminLicenses();
    const updated = [license, ...registry.filter(l => l.key !== key)];
    try {
      localStorage.setItem(ADMIN_LICENSES_KEY, JSON.stringify(updated));
    } catch (e) {
      console.error('Error saving admin license:', e);
    }

    return license;
  }

  /**
   * Reads raw admin license array from storage without auto-seeding
   */
  public static getRawAdminLicenses(): LicenseInfo[] {
    try {
      const saved = localStorage.getItem(ADMIN_LICENSES_KEY);
      if (saved) {
        return JSON.parse(saved);
      }
    } catch (e) {
      console.error('Error loading raw admin licenses:', e);
    }
    return [];
  }

  /**
   * Gets list of licenses generated by the Admin (with initial enterprise seed if empty)
   */
  public static getAdminLicenses(): LicenseInfo[] {
    const raw = this.getRawAdminLicenses();
    if (raw && raw.length > 0) {
      return raw;
    }
    return this.seedEnterpriseLicenses();
  }

  /**
   * Auto-seeds official corporate licenses for client companies
   */
  public static seedEnterpriseLicenses(): LicenseInfo[] {
    const tepic = this.generateAdminLicense(
      '365D',
      'Licencia Oficial Sala y Barra (15 Empleados)',
      'tepic-madrid',
      'Restaurante Tepic (Ayala 14)',
      15
    );
    const lovo = this.generateAdminLicense(
      '365D',
      'Licencia Oficial Trilogía Cócteles (10 Empleados)',
      'lovo-bar',
      'LOVO Bar & Hospitality',
      10
    );
    return [tepic, lovo];
  }

  /**
   * Helper to retrieve official active license for a company workspace (generates one if not yet present)
   */
  public static getOfficialLicenseForWorkspace(workspaceId: string): LicenseInfo {
    const licenses = this.getAdminLicenses();
    const found = licenses.find(l => l.workspaceId === workspaceId && !l.isRevoked);
    if (found) return found;

    const compName = workspaceId === 'tepic-madrid'
      ? 'Restaurante Tepic (Ayala 14)'
      : workspaceId === 'lovo-bar'
      ? 'LOVO Bar & Hospitality'
      : workspaceId;
    const seats = workspaceId === 'tepic-madrid' ? 15 : 10;
    return this.generateAdminLicense('365D', `Licencia Oficial Corporativa (${seats} Empleados)`, workspaceId, compName, seats);
  }

  /**
   * Revokes an admin-issued license
   */
  public static revokeAdminLicense(key: string): void {
    const registry = this.getAdminLicenses();
    const updated = registry.map(l => l.key === key ? { ...l, isRevoked: true } : l);
    localStorage.setItem(ADMIN_LICENSES_KEY, JSON.stringify(updated));

    // If currently active on this device, revoke it locally too
    const current = this.getSubscriptionState();
    if (current.activeLicense?.key === key) {
      localStorage.removeItem(USER_SUB_STORAGE_KEY);
    }
  }

  /**
   * Validates a license key format and checksum
   */
  public static validateKey(key: string): { valid: boolean; plan?: SubscriptionPlan; expiresAt?: number; message?: string } {
    if (!key) return { valid: false, message: 'Ingresa un código de licencia.' };

    const clean = key.trim().toUpperCase();

    // Friendly corporate aliases for demo & onboarding
    if (clean.includes('TEPIC')) {
      const tepicLic = this.getOfficialLicenseForWorkspace('tepic-madrid');
      return { valid: true, plan: tepicLic.plan, expiresAt: tepicLic.expiresAt };
    }
    if (clean.includes('LOVO')) {
      const lovoLic = this.getOfficialLicenseForWorkspace('lovo-bar');
      return { valid: true, plan: lovoLic.plan, expiresAt: lovoLic.expiresAt };
    }

    const parts = clean.split('-');

    if (parts.length !== 4 || parts[0] !== 'PB') {
      return { valid: false, message: 'Formato de licencia inválido (ej: PB-30D-...)' };
    }

    const plan = parts[1] as SubscriptionPlan;
    if (!['30D', '90D', '365D', 'LIFETIME'].includes(plan)) {
      return { valid: false, message: 'Plan no reconocido en la licencia.' };
    }

    const expiryMs = parseInt(parts[2], 16);
    if (isNaN(expiryMs)) {
      return { valid: false, message: 'Fecha de expiración corrupta en la clave.' };
    }

    const expectedChecksum = this.generateChecksum(plan, expiryMs);
    if (parts[3] !== expectedChecksum) {
      return { valid: false, message: 'Clave de licencia no auténtica o alterada.' };
    }

    // Check if revoked in admin registry
    const registry = this.getAdminLicenses();
    const foundInRegistry = registry.find(l => l.key === clean);
    if (foundInRegistry && foundInRegistry.isRevoked) {
      return { valid: false, message: 'Esta licencia ha sido revocada por el administrador.' };
    }

    if (Date.now() > expiryMs) {
      return { valid: false, message: 'Esta licencia ha expirado.' };
    }

    return { valid: true, plan, expiresAt: expiryMs };
  }

  /**
   * Activates a license key on the current user's device
   */
  public static activateLicense(key: string, targetWorkspaceId?: string): { success: boolean; message: string; license?: LicenseInfo } {
    const cleanKey = key.trim().toUpperCase();

    // Check aliases
    if (cleanKey.includes('TEPIC')) {
      const tepicLic = this.getOfficialLicenseForWorkspace('tepic-madrid');
      const state: UserSubscriptionState = {
        status: 'active',
        freeTrialsUsed: 1,
        maxFreeTrials: 1,
        activeLicense: tepicLic
      };
      localStorage.setItem(USER_SUB_STORAGE_KEY, JSON.stringify(state));
      CloudSyncService.setCurrentWorkspaceId('tepic-madrid');
      return {
        success: true,
        message: `¡Licencia corporativa activada para Restaurante Tepic! (${tepicLic.employeeSeats || 15} empleados)`,
        license: tepicLic
      };
    }
    if (cleanKey.includes('LOVO')) {
      const lovoLic = this.getOfficialLicenseForWorkspace('lovo-bar');
      const state: UserSubscriptionState = {
        status: 'active',
        freeTrialsUsed: 1,
        maxFreeTrials: 1,
        activeLicense: lovoLic
      };
      localStorage.setItem(USER_SUB_STORAGE_KEY, JSON.stringify(state));
      CloudSyncService.setCurrentWorkspaceId('lovo-bar');
      return {
        success: true,
        message: `¡Licencia corporativa activada para LOVO Bar Madrid! (${lovoLic.employeeSeats || 10} empleados)`,
        license: lovoLic
      };
    }

    const validation = this.validateKey(key);
    if (!validation.valid || !validation.plan || !validation.expiresAt) {
      return { success: false, message: validation.message || 'Licencia inválida' };
    }

    const details = this.getPlanDetails(validation.plan);

    // Look for existing license metadata in admin registry
    const registry = this.getAdminLicenses();
    const found = registry.find(l => l.key === cleanKey);

    const ws = targetWorkspaceId || found?.workspaceId || 'default';
    const compName = found?.companyName || (ws === 'tepic-madrid' ? 'Restaurante Tepic (Ayala 14)' : ws === 'lovo-bar' ? 'LOVO Bar & Hospitality' : 'General');
    const seats = found?.employeeSeats || 10;

    const license: LicenseInfo = {
      key: cleanKey,
      plan: validation.plan,
      planName: details.name,
      createdAt: Date.now(),
      expiresAt: validation.expiresAt,
      workspaceId: ws,
      companyName: compName,
      employeeSeats: seats,
      clientNotes: found?.clientNotes
    };

    const state: UserSubscriptionState = {
      status: 'active',
      freeTrialsUsed: 1,
      maxFreeTrials: 1,
      activeLicense: license
    };

    try {
      localStorage.setItem(USER_SUB_STORAGE_KEY, JSON.stringify(state));
      // Auto-bind device to the company workspace
      if (ws) {
        CloudSyncService.setCurrentWorkspaceId(ws);
      }
    } catch (e) {
      console.error('Error activating license:', e);
    }

    return {
      success: true,
      message: `¡Licencia corporativa activada para ${compName}! (${seats} accesos de empleados)`,
      license
    };
  }

  /**
   * Retrieves current user subscription state
   */
  public static getSubscriptionState(): UserSubscriptionState {
    const defaultState: UserSubscriptionState = {
      status: 'free_trial',
      freeTrialsUsed: 0,
      maxFreeTrials: 1
    };

    try {
      const saved = localStorage.getItem(USER_SUB_STORAGE_KEY);
      if (!saved) {
        return defaultState;
      }

      const parsed: UserSubscriptionState = JSON.parse(saved);

      // If active license is present, verify expiration
      if (parsed.activeLicense) {
        const now = Date.now();
        if (now > parsed.activeLicense.expiresAt) {
          // Expired
          return {
            status: 'expired',
            freeTrialsUsed: parsed.freeTrialsUsed || 1,
            maxFreeTrials: 1,
            activeLicense: parsed.activeLicense,
            daysRemaining: 0
          };
        }

        const msLeft = parsed.activeLicense.expiresAt - now;
        const daysRemaining = Math.max(1, Math.ceil(msLeft / (1000 * 60 * 60 * 24)));

        return {
          status: 'active',
          freeTrialsUsed: parsed.freeTrialsUsed || 1,
          maxFreeTrials: 1,
          activeLicense: parsed.activeLicense,
          daysRemaining
        };
      }

      // If in free trial but exhausted
      if (parsed.freeTrialsUsed >= 1) {
        return {
          status: 'expired',
          freeTrialsUsed: parsed.freeTrialsUsed,
          maxFreeTrials: 1
        };
      }

      return {
        status: 'free_trial',
        freeTrialsUsed: parsed.freeTrialsUsed || 0,
        maxFreeTrials: 1
      };
    } catch (e) {
      console.error('Error reading subscription state:', e);
      return defaultState;
    }
  }

  /**
   * Checks if user is permitted to start a new simulation
   */
  public static canStartSimulation(): { allowed: boolean; reason: 'active' | 'free_trial' | 'trial_exhausted' | 'expired'; daysRemaining?: number } {
    const state = this.getSubscriptionState();

    if (state.status === 'active') {
      return { allowed: true, reason: 'active', daysRemaining: state.daysRemaining };
    }

    if (state.status === 'free_trial' && state.freeTrialsUsed < state.maxFreeTrials) {
      return { allowed: true, reason: 'free_trial' };
    }

    if (state.status === 'expired' && state.activeLicense) {
      return { allowed: false, reason: 'expired' };
    }

    return { allowed: false, reason: 'trial_exhausted' };
  }

  /**
   * Consumes one simulation credit if on free trial
   */
  public static recordSimulationStarted(): void {
    const state = this.getSubscriptionState();
    if (state.status === 'free_trial') {
      const updated: UserSubscriptionState = {
        ...state,
        freeTrialsUsed: (state.freeTrialsUsed || 0) + 1,
        status: 'expired'
      };
      localStorage.setItem(USER_SUB_STORAGE_KEY, JSON.stringify(updated));
    }
  }

  /**
   * Checks current URL query params (?key=PB-... or ?license=PB-...) for auto-activation
   */
  public static checkUrlForActivationKey(): { activated: boolean; license?: LicenseInfo; message?: string } {
    if (typeof window === 'undefined') return { activated: false };

    try {
      const urlParams = new URLSearchParams(window.location.search);
      const keyFromUrl = urlParams.get('key') || urlParams.get('license');
      const companyFromUrl = urlParams.get('company') || urlParams.get('workspace');

      if (companyFromUrl) {
        CloudSyncService.setCurrentWorkspaceId(companyFromUrl);
      }

      if (keyFromUrl) {
        const result = this.activateLicense(keyFromUrl, companyFromUrl || undefined);
        // Clean up URL parameters cleanly without reloading page
        const newUrl = window.location.pathname;
        window.history.replaceState({}, document.title, newUrl);

        return {
          activated: result.success,
          license: result.license,
          message: result.message
        };
      }
    } catch (e) {
      console.error('Error checking activation URL:', e);
    }

    return { activated: false };
  }

  /**
   * Generates a Magic Activation Link for a given key, optionally locked to a company workspace
   */
  public static getMagicLink(key: string, workspaceId?: string): string {
    if (typeof window === 'undefined') return key;
    const origin = window.location.origin;
    let url = `${origin}/?key=${encodeURIComponent(key)}`;
    if (workspaceId && workspaceId !== 'default') {
      url += `&company=${encodeURIComponent(workspaceId)}`;
    }
    return url;
  }

  /**
   * Resets local subscription state (for testing purposes)
   */
  public static resetLocalSubscription(): void {
    localStorage.removeItem(USER_SUB_STORAGE_KEY);
  }
}
